-- ============================================
-- 13. 玩家角色 (Player Character)
-- ============================================
DROP TABLE IF EXISTS player_character;
CREATE TABLE player_character (
    id VARCHAR(100) PRIMARY KEY,
    name VARCHAR(100) NOT NULL COMMENT '角色名称',
    subtitle VARCHAR(200) COMMENT '简短描述',
    summary TEXT COMMENT '概述',
    player_name VARCHAR(100) COMMENT '玩家姓名',
    level INT NOT NULL DEFAULT 1 COMMENT '等级',
    race_id VARCHAR(100) COMMENT '种族ID',
    class_id VARCHAR(100) COMMENT '职业ID',
    strength INT DEFAULT 10 COMMENT '力量',
    dexterity INT DEFAULT 10 COMMENT '敏捷',
    constitution INT DEFAULT 10 COMMENT '体质',
    intelligence INT DEFAULT 10 COMMENT '智力',
    wisdom INT DEFAULT 10 COMMENT '感知',
    charisma INT DEFAULT 10 COMMENT '魅力',
    weapon_id VARCHAR(100) DEFAULT NULL COMMENT '装备的武器ID',
    armor_id VARCHAR(100) DEFAULT NULL COMMENT '装备的护甲ID',
    feat_ids JSON COMMENT '专长ID列表',
    spell_ids JSON COMMENT '法术ID列表',
    tags JSON,
    details JSON,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ============================================
-- 14. 角色背包 (Character Inventory)
-- ============================================
DROP TABLE IF EXISTS character_inventory;
CREATE TABLE character_inventory (
    id VARCHAR(100) PRIMARY KEY,
    character_id VARCHAR(100) NOT NULL COMMENT '角色ID',
    item_type VARCHAR(20) NOT NULL COMMENT '类型: weapon/armor/magic_item/consumable',
    item_id VARCHAR(100) NOT NULL COMMENT '物品ID',
    item_name VARCHAR(100) NOT NULL COMMENT '物品名称',
    quantity INT DEFAULT 1 COMMENT '数量',
    equipped TINYINT(1) DEFAULT 0 COMMENT '是否装备中',
    obtained_at DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '获得时间',
    INDEX idx_character (character_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

